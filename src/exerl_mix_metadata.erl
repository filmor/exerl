-module(exerl_mix_metadata).

-include("exerl.hrl").

-export([prepare/1, generate/1]).

-define(GENERATED, ~"% Generated by exerl; do not edit.\n").

-doc "Prepare local Mix dependencies before rebar discovers their dependencies.".
-spec prepare(rebar_state:t()) -> ok.
prepare(State) ->
    DepsDir = rebar_dir:deps_dir(State),
    Dirs = [rebar_dir:checkouts_dir(State), DepsDir],
    Profiles = rebar_state:current_profiles(State),
    Deps = lists:append([
        rebar_state:get(State, {deps, Profile}, []) ++
            rebar_state:get(State, {locks, Profile}, [])
     || Profile <- Profiles
    ]),
    SubDirs = lists:filtermap(
        fun
            ({Name, {git_subdir, _, _, SubDir}}) ->
                {true, filename:join([DepsDir, exerl_util:ensure_string(Name), SubDir])};
            ({Name, {git_subdir, _, _, SubDir}, _}) ->
                {true, filename:join([DepsDir, exerl_util:ensure_string(Name), SubDir])};
            ({Name, _, {git_subdir, _, _, SubDir}}) ->
                {true, filename:join([DepsDir, exerl_util:ensure_string(Name), SubDir])};
            (_) ->
                false
        end,
        Deps
    ),
    Apps = lists:append([filelib:wildcard(filename:join(Dir, "*")) || Dir <- Dirs]),
    lists:foreach(
        fun generate/1,
        lists:usort(Apps ++ SubDirs)
    ).

-doc "Generate Hex metadata and rebar dependency configuration for a Mix project.".
-spec generate(file:filename_all()) -> ok.
generate(Dir) ->
    Config = filename:join(Dir, "rebar.config"),
    case
        filelib:is_regular(filename:join(Dir, "mix.exs")) andalso
            not filelib:is_regular(filename:join(Dir, "rebar.config.script")) andalso
            generated_config(Config)
    of
        true ->
            generate_metadata(Dir);
        false ->
            ok
    end.

generated_config(Config) ->
    case file:read_file(Config) of
        {error, enoent} ->
            Dir = filename:dirname(Config),
            not filelib:is_regular(filename:join(Dir, "hex_metadata.config"));
        {ok, Data} ->
            string:prefix(Data, ?GENERATED) =/= nomatch;
        {error, Reason} ->
            error({read_mix_config, Config, Reason})
    end.

generate_metadata(Dir) ->
    exerl_util:ensure_elixir(),
    {ok, Cwd} = file:get_cwd(),
    Env = ?Mix:env(),
    Undefined = ?Code:get_compiler_option(no_warn_undefined),
    rebar_api:debug("Generating Mix metadata in ~ts", [Dir]),
    try
        ok = file:set_cwd(Dir),
        ?Mix:env(prod),
        ?ProjectStack:on_clean_slate(fun() ->
            ?Task:run(~"local.hex", [~"--force", ~"--if-missing"]),
            'Elixir.Mix.Local':append_archives(),
            ?Code:put_compiler_option(no_warn_undefined, all),
            Modules = ?Code:compile_file(~"mix.exs"),
            try
                'Elixir.Hex':start(),
                write_metadata('Elixir.Mix.Tasks.Hex.Build':prepare_package())
            after
                lists:foreach(
                    fun({Module, _}) ->
                        code:delete(Module),
                        code:purge(Module)
                    end,
                    Modules
                )
            end
        end)
    after
        ?Code:put_compiler_option(no_warn_undefined, Undefined),
        ?Mix:env(Env),
        ok = file:set_cwd(Cwd)
    end.

write_metadata(#{exclude_deps := [_ | _] = Excluded}) ->
    rebar_api:abort(
        "Cannot generate rebar metadata for non-Hex dependencies: ~ts",
        [lists:join(", ", [atom_to_list(App) || App <- Excluded])]
    );
write_metadata(#{meta := Meta, exclude_deps := []}) ->
    {ok, MixFile} = file:read_file("mix.exs"),
    #{tarball := Tarball} = 'Elixir.Hex.Tar':'create!'(
        Meta, [{~"mix.exs", MixFile}], memory
    ),
    {ok, Files} = erl_tar:extract({binary, Tarball}, [memory]),
    {"metadata.config", Metadata} = lists:keyfind("metadata.config", 1, Files),
    Deps = [
        {App, binary_to_list(Requirement), {pkg, binary_to_list(Name)}}
     || #{app := App, name := Name, requirement := Requirement, optional := false} <-
            maps:get(requirements, Meta)
    ],
    ok = file:write_file("hex_metadata.config", Metadata),
    ok = file:write_file("rebar.config", [?GENERATED, io_lib:format("~p.~n", [{deps, Deps}])]).
